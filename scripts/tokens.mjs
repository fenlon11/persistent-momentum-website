#!/usr/bin/env node
// Design tokens → app/globals.css (fenlon11/pmOS#942).
//
// The site's colours, type, spacing and radii come from tokens/design-tokens.json, a copy of pmOS
// projects/persistent-momentum/design-tokens.json (BRAND.md §Palette is the source). This script
// writes them into the marked block at the top of app/globals.css, so Tailwind and the
// design-sync extractor keep reading CSS variables from that one file.
//
//   node scripts/tokens.mjs           regenerate the block
//   node scripts/tokens.mjs --check   exit 1 if the block is out of date (scripts/audit-theme.mjs runs this in build)
//   node scripts/tokens.mjs --sync    copy the pmOS token file in first, then regenerate
//                                     (PM_DESIGN_TOKENS overrides the source path)
//
// Vercel builds this repo alone, so the copy is committed; --sync is how a token change reaches it.

import { copyFileSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const BRAND_FILE = join(ROOT, 'tokens/design-tokens.json');
const SITE_FILE = join(ROOT, 'tokens/site-tokens.json');
const CSS_FILE = join(ROOT, 'app/globals.css');
const PMOS_TOKENS = join(homedir(), 'pmOS/projects/persistent-momentum/design-tokens.json');

export const START = '/* tokens:start';
export const END = '/* tokens:end */';

// The site's existing variable names (shared with the PW site so components can move between
// them) → the design-system role each one now carries. Light theme only.
const ROLE_VARS = {
  'color-bg': 'background',
  'color-bg-secondary': 'surfaceAlt',
  'color-bg-card': 'surface',
  'color-bg-light': 'surfaceAlt',
  'color-bg-light-secondary': 'surfaceAlt',
  'color-bg-light-card': 'surface',
  'color-text': 'text',
  // Mid-Gray fails 4.5:1 for small text; DESIGN-SYSTEM.md puts small secondary text in Royal Blue.
  'color-text-muted': 'textSecondary',
  'color-text-dark': 'text',
  'color-text-dark-muted': 'textSecondary',
  'color-primary': 'accent',
  'color-border': 'border',
  'color-border-light': 'border',
  'color-secondary': 'surfaceAlt',
  'color-accent': 'accent',
};

// Named palette slots the navy hero/footer bands use directly.
const PALETTE_VARS = {
  'color-navy': 'deepNavy',
  'color-navy-2': 'royalBlue',
  'color-electric': 'electricBlue',
  'color-ice': 'iceBlue',
  'color-glow-white': 'glowWhite',
  'color-primary-glow': 'iceBlue',
};

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const px = (n) => (n === 0 ? '0' : `${n}px`);
// Type and space scale with the browser's default font size: px ÷ 16 (equal to the px value at a 16px root).
const rem = (n) => (n === 0 ? '0' : `${n / 16}rem`);

function rgba(hex, alpha) {
  const n = parseInt(hex.slice(1), 16);
  return `rgb(${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255} / ${alpha})`;
}

export function renderBlock(brand, site) {
  const palette = brand.color.palette;
  const role = brand.color.role.light;
  const paletteVar = (key) => {
    if (!palette[key]) throw new Error(`design-tokens.json: no palette key "${key}"`);
    return `var(--pm-${kebab(key)})`;
  };
  const roleValue = (name) => {
    const r = role[name];
    if (!r) throw new Error(`design-tokens.json: no light role "${name}"`);
    return r.alpha === undefined ? paletteVar(r.ref) : rgba(palette[r.ref].hex, r.alpha);
  };

  const lines = [
    `${START} — generated by scripts/tokens.mjs from tokens/design-tokens.json v${brand.version} and tokens/site-tokens.json. Do not edit by hand: change the JSON, then run \`npm run tokens\`. */`,
    ':root {',
    '  /* Palette — BRAND.md §Palette */',
    ...Object.entries(palette).map(([k, v]) => `  --pm-${kebab(k)}: ${v.hex};`),
    '',
    '  /* Roles (light) */',
    ...Object.entries(ROLE_VARS).map(([v, r]) => `  --${v}: ${roleValue(r)};`),
    // DESIGN-SYSTEM.md primary button recipe: hover darkens via an 8% Deep Navy overlay.
    `  --color-primary-hover: color-mix(in srgb, ${roleValue('accent')} 92%, ${paletteVar('deepNavy')});`,
    ...Object.entries(PALETTE_VARS).map(([v, k]) => `  --${v}: ${paletteVar(k)};`),
    '',
    '  /* Site-only colours BRAND.md does not define (tokens/site-tokens.json) */',
    ...Object.entries(site.color).map(([k, hex]) => `  --color-${kebab(k)}: ${hex};`),
    '',
    '  /* Type scale */',
    ...Object.entries(brand.typeScale).flatMap(([step, t]) => [
      `  --pm-text-${step}: ${rem(t.size)};`,
      `  --pm-leading-${step}: ${t.lineHeight};`,
    ]),
    '',
    '  /* Space (4px base) */',
    ...Object.entries(brand.space).map(([k, v]) => `  --pm-space-${k}: ${rem(v)};`),
    '',
    '  /* Radii */',
    ...Object.entries(brand.radius).map(([k, v]) => `  --pm-radius-${k}: ${px(v)};`),
    '  --radius: var(--pm-radius-sm);',
    '  --radius-sm: var(--pm-radius-sm);',
    '  --radius-lg: var(--pm-radius-md);',
    '',
    '  /* Fonts — --font-inter is set on <html> by next/font in app/layout.tsx */',
    `  --font-body: var(--font-inter), ${brand.font.sans.stack};`,
    '}',
    END,
  ];
  return lines.join('\n');
}

export function readTokens() {
  return {
    brand: JSON.parse(readFileSync(BRAND_FILE, 'utf8')),
    site: JSON.parse(readFileSync(SITE_FILE, 'utf8')),
  };
}

// Replace (or report) the block between the markers. Returns the new CSS text.
export function applyBlock(css, block) {
  const s = css.indexOf(START);
  const e = css.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error(`app/globals.css: token markers not found ("${START}" … "${END}")`);
  return css.slice(0, s) + block + css.slice(e + END.length);
}

export function blockIsCurrent() {
  const { brand, site } = readTokens();
  const css = readFileSync(CSS_FILE, 'utf8');
  return applyBlock(css, renderBlock(brand, site)) === css;
}

if (fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  const args = process.argv.slice(2);
  if (args.includes('--sync')) {
    const src = process.env.PM_DESIGN_TOKENS || PMOS_TOKENS;
    copyFileSync(src, BRAND_FILE);
    console.log(`[tokens] copied ${src} → tokens/design-tokens.json`);
  }
  if (args.includes('--check')) {
    if (!blockIsCurrent()) {
      console.error('[tokens] app/globals.css token block is out of date with tokens/*.json. Run `npm run tokens`.');
      process.exit(1);
    }
    console.log('[tokens] app/globals.css token block is current');
  } else {
    const { brand, site } = readTokens();
    const css = readFileSync(CSS_FILE, 'utf8');
    writeFileSync(CSS_FILE, applyBlock(css, renderBlock(brand, site)));
    console.log(`[tokens] wrote app/globals.css token block (design-tokens v${brand.version})`);
  }
}
